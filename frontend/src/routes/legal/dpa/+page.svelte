<h1>Data Processing Agreement</h1>
<p class="text-text-muted text-sm mb-2">Information for this Hash installation</p>

<h2>Request the applicable agreement</h2>
<p>
  A data processing agreement concerns the organisations involved in operating and using a
  particular Hash installation. Contact your organisation's administrator or the installation's
  operator for the applicable agreement and its schedules. This page is general information and
  is not an executed agreement.
</p>

<h2>Deployment-specific details</h2>
<p>
  The agreement and schedules need to reflect the parties, processing instructions, categories of
  data, security measures, service providers, processing locations, retention, and arrangements for
  privacy requests and the end of the service. Those details depend on how this installation is
  operated and which integrations are enabled.
</p>
<p>
  Retention and deletion arrangements need to account for the evidence-retention period disclosed
  in the signing page and any immutable storage used by the installation. The software's licence
  does not supply a data processing agreement for its operator.
</p>

<h2>Privacy contact</h2>
<p>
  The signing page identifies the document sender and this installation's operator, with their
  configured contacts and privacy-policy link. Account holders can request the same information
  from their organisation's administrator. See the <a href="/legal/privacy">privacy information</a>
  for more guidance.
</p>
