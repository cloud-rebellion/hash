// The actual SDK event is encoded here, without a network or provider. The
// separate tagged test exercises the registered MCP/credential/native-PG path.
type mcpPreviewSignalTransportV1 struct {
	mu     sync.Mutex
	events [][]byte
}

func (*mcpPreviewSignalTransportV1) Configure(sentry.ClientOptions)        {}
func (*mcpPreviewSignalTransportV1) Flush(time.Duration) bool              { return true }
func (*mcpPreviewSignalTransportV1) FlushWithContext(context.Context) bool { return true }
func (*mcpPreviewSignalTransportV1) Close()                                {}
func (p *mcpPreviewSignalTransportV1) SendEvent(event *sentry.Event) {
	raw, err := json.Marshal(event)
	if err != nil {
		panic(err)
	}
	p.mu.Lock()
	defer p.mu.Unlock()
	p.events = append(p.events, raw)
}
func (p *mcpPreviewSignalTransportV1) failureEvents(t *testing.T) []sentry.Event {
	t.Helper()
	p.mu.Lock()
	defer p.mu.Unlock()
	var events []sentry.Event
	for _, raw := range p.events {
		var event sentry.Event
		if err := json.Unmarshal(raw, &event); err != nil {
			t.Fatal(err)
		}
		if event.Type != "transaction" {
			events = append(events, event)
		}
	}
	return events
}

func mcpPreviewSignalHubV1(t *testing.T) (*sentry.Hub, *mcpPreviewSignalTransportV1) {
	t.Helper()
	wire := &mcpPreviewSignalTransportV1{}
	client, err := sentry.NewClient(sentry.ClientOptions{Dsn: "https://fixture-public@flare.invalid/1", Transport: wire,
		EnableTracing: true, TracesSampleRate: 1, DisableLogs: true, DisableMetrics: true})
	if err != nil {
		t.Fatal(err)
	}
	return sentry.NewHub(client, sentry.NewScope()), wire
}

func TestMCPPreviewFailureSignalsBeforePublicMaskV1(t *testing.T) {
	t.Setenv("FLARE_TRACES_SAMPLE_RATE", "1")
	const private = "PRIVATE_PREVIEW_CONTRACT_AUTH_PARSER_V1"
	for _, test := range []struct {
		name       string
		err        error
		contextEnd string
		category   string
	}{
		{"render dependency", errHTMLTemplatePreviewRenderV1, "", "dependency"},
		{"generated invalid PDF", errors.Join(errHTMLTemplatePreviewInvalidV1, sanitize.ErrPDFInvalid, errors.New(private)), "", "internal"},
		{"worker unavailable", errors.Join(errHTMLTemplatePreviewInvalidV1, sanitize.ErrPDFWorkerUnavailable), "", "dependency"},
		{"scanner unavailable", malwarescan.ErrUnavailable, "", "dependency"},
		{"typed timeout", context.DeadlineExceeded, "", "timeout"},
		{"render lost deadline cause", errHTMLTemplatePreviewRenderV1, "deadline", "timeout"},
		{"success", nil, "", ""},
		{"revoked credential", auth.ErrMutationPermissionRevoked, "", ""},
		{"expired credential", auth.ErrMutationCredentialExpired, "", ""},
		{"stale template", errHTMLTemplateConflict, "", ""},
		{"missing template", errTemplateNotFound, "", ""},
		{"invalid master", htmlmaster.ErrInvalid, "", ""},
		{"master limit", htmlmaster.ErrLimit, "", ""},
		{"missing values", htmlmaster.ErrMissingValues, "", ""},
		{"incomplete contract", htmlmaster.ErrContractIncomplete, "", ""},
		{"human review", errHumanReviewRequiredV1, "", ""},
		{"preview receipt", errHTMLTemplatePreviewReceipt, "", ""},
		{"capacity", errors.Join(errHTMLTemplatePreviewInvalidV1, sanitize.ErrPDFWorkerCapacity), "", ""},
		{"byte policy", errors.Join(errHTMLTemplatePreviewInvalidV1, sanitize.ErrPDFTooLarge), "", ""},
		{"generated byte policy", errors.Join(errHTMLTemplatePreviewInvalidV1, errHTMLTemplatePreviewOutputLimitV1), "", ""},
		{"renderer response byte policy", errors.Join(errHTMLTemplatePreviewRenderV1, render.ErrPDFResponseTooLarge), "", ""},
		{"page policy", errors.Join(errHTMLTemplatePreviewInvalidV1, sanitize.ErrTooManyPages), "", ""},
		{"malware refusal", malwarescan.ErrDetected, "", ""},
		{"cancellation", context.Canceled, "", ""},
		{"caller canceled render", errHTMLTemplatePreviewRenderV1, "cancel", ""},
		{"auth before elapsed deadline", auth.ErrMutationPermissionRevoked, "deadline", ""},
		{"masked text is not a classifier", errors.New("native design operation unavailable or refused"), "", ""},
	} {
		t.Run(test.name, func(t *testing.T) {
			hub, wire := mcpPreviewSignalHubV1(t)
			hub.Scope().SetUser(sentry.User{Email: private})
			hub.Scope().SetContext("private", sentry.Context{"body": private})
			hub.Scope().SetTag("private", private)
			r := httptest.NewRequest("POST", "https://hash.example/mcp?private="+private, strings.NewReader(private))
			r.Header.Set("Authorization", "Bearer "+private)
			r.Header.Set("X-Request-Id", private)
			r.Header.Set("sentry-trace", strings.Repeat("1", 32)+"-"+strings.Repeat("2", 16)+"-1")
			hub.Scope().SetRequest(r)
			r = r.WithContext(sentry.SetHubOnContext(r.Context(), hub))
			r, finish := flarereport.BeginHTTPRequest(r)
			ctx := r.Context()
			switch test.contextEnd {
			case "deadline":
				var cancel context.CancelFunc
				ctx, cancel = context.WithDeadline(ctx, time.Now().Add(-time.Second))
				defer cancel()
			case "cancel":
				var cancel context.CancelFunc
				ctx, cancel = context.WithCancel(ctx)
				cancel()
			}
			captureMCPPreviewFailureV1(ctx, test.err)
			captureMCPPreviewFailureV1(ctx, test.err) // existing HTTP dedup, not a new queue
			finish(200, "/mcp")
			events := wire.failureEvents(t)
			want := 0
			if test.category != "" {
				want = 1
			}
			if len(events) != want {
				t.Fatalf("failure events=%d want=%d", len(events), want)
			}
			for _, event := range events {
				if event.Tags["operation"] != "mcp" || event.Tags["failure_category"] != test.category || event.Level != sentry.LevelError {
					t.Fatal("fixed operation/category missing", event.Tags)
				}
				if fmt.Sprint(event.Contexts["trace"]["trace_id"]) != strings.Repeat("1", 32) {
					t.Fatal("existing safe trace correlation lost")
				}
			}
			wire.mu.Lock()
			defer wire.mu.Unlock()
			for _, raw := range wire.events {
				if strings.Contains(string(raw), private) {
					t.Fatal("private context/parser/auth text reached telemetry")
				}
			}
			if public := safeMCPDesignFailureV1(test.err); public != nil && strings.Contains(public.Error(), private) {
				t.Fatal("private cause reached public design failure")
			}
		})
	}
}
