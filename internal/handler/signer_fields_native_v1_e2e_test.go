func TestOwnedSignerFieldsNativeBatchRollbackAndRepeatE2E(t *testing.T) {
	q := newOwnedPublicReadFixtureV1(t)
	ownedCreationPrepareProPlanV1(t, q)
	f := q.f
	f.s.Sign.Storage = f.s.Storage
	actor := sendengine.Actor{UserID: &f.user.ID, OrgID: f.org, Via: "test", LawfulBasis: "contract", Authorize: func(_ context.Context, _ pgx.Tx, user *generated.User) error {
		if user == nil || user.ID != f.user.ID || user.OrgID != f.org || user.Role != "owner" {
			return auth.ErrMutationPermissionRevoked
		}
		return nil
	}}
	doc, party, field, signature, invitation := ownedRealBrowserManualAutosaveV1(t, q, fieldBrowserPDF("Reviewed native autosave rollback"), 1, actor)
	token := strings.TrimPrefix(invitation.Path, "/sign/")
	rc := q.lookupV1(t, token)
	notice, err := f.s.signerPrivacyNotice(signerReadRequestE2E(token, ""), rc)
	if err != nil {
		t.Fatal(err)
	}
	if err = rc.CloseReadV1(); err != nil {
		t.Fatal(err)
	}
	q.assertObserversOnlyV1(t)
	post := func(values []submitFieldValueInput) *httptest.ResponseRecorder {
		t.Helper()
		body, err := json.Marshal(submitFieldsInput{Values: values})
		if err != nil {
			t.Fatal(err)
		}
		r := httptest.NewRequest(http.MethodPost, "/sign/"+token+"/fields", bytes.NewReader(body)).WithContext(f.ctx)
		r.Header.Set("Content-Type", "application/json")
		r.Header.Set(signerNoticeDigestHeader, notice.NoticeDigest)
		w := httptest.NewRecorder()
		f.s.Routes().ServeHTTP(w, r)
		q.assertObserversOnlyV1(t)
		return w
	}
	snapshot := func() string {
		t.Helper()
		var result string
		err := f.pool.QueryRow(f.ctx, `SELECT jsonb_build_object('fields',(SELECT jsonb_agg(jsonb_build_object('id',id,'value',value,'completed',completed_at) ORDER BY id) FROM document_fields WHERE document_id=$1),'events',(SELECT count(*) FROM events WHERE document_id=$1 AND kind='document.field_filled'),'measurements',(SELECT count(*) FROM html_snapshot_event_payload_sizes_v1 m JOIN events e ON e.id=m.event_id WHERE e.document_id=$1 AND e.kind='document.field_filled'),'head',(SELECT encode(row_hash,'hex') FROM events WHERE org_id=$2 ORDER BY created_at DESC,id DESC LIMIT 1))::text`, doc.ID, f.org).Scan(&result) //nolint:rawsql -- read-only atomic field/audit/M94/chain witness
		if err != nil {
			t.Fatal(err)
		}
		return result
	}
	before := snapshot()
	for _, tc := range []struct {
		name   string
		values []submitFieldValueInput
		status int
	}{
		{"signature", []submitFieldValueInput{{FieldID: field.ID.String(), Value: "must roll back"}, {FieldID: signature.ID.String(), Value: "cannot fill signature"}}, http.StatusBadRequest},
		{"duplicate", []submitFieldValueInput{{FieldID: field.ID.String(), Value: "first"}, {FieldID: field.ID.String(), Value: "duplicate"}}, http.StatusBadRequest},
		{"foreign", []submitFieldValueInput{{FieldID: field.ID.String(), Value: "must roll back"}, {FieldID: uuid.NewString(), Value: "foreign"}}, http.StatusForbidden},
		{"oversize", []submitFieldValueInput{{FieldID: field.ID.String(), Value: strings.Repeat("x", maxSignerFieldValueBytes+1)}}, http.StatusBadRequest},
	} {
		t.Run(tc.name, func(t *testing.T) {
			w := post(tc.values)
			if w.Code != tc.status || w.Header().Get("X-Hash-PDF-SHA256") != "" {
				t.Fatalf("refused native batch status=%d", w.Code)
			}
			if snapshot() != before {
				t.Fatal("refused batch changed fields/audit/measurements/chain")
			}
		})
	}
	// The real native event INSERT fails after the actual field UPDATE. Both
	// must roll back together; no test creates or repairs a measurement record.
	_, err = f.pool.Exec(f.ctx, `CREATE FUNCTION hash_test_fail_native_field_event() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'controlled native field audit outage'; END $$`)
	if err != nil {
		t.Fatal(err)
	} //nolint:rawsql -- isolated disposable database failure injection
	_, err = f.pool.Exec(f.ctx, `CREATE TRIGGER hash_test_native_field_event_outage BEFORE INSERT ON events FOR EACH ROW WHEN (NEW.document_id='`+doc.ID.String()+`'::uuid AND NEW.kind='document.field_filled') EXECUTE FUNCTION hash_test_fail_native_field_event()`)
	if err != nil {
		t.Fatal(err)
	} //nolint:rawsql -- UUID generated by genuine writer, no caller SQL
	t.Cleanup(func() {
		_, _ = f.pool.Exec(context.Background(), `DROP TRIGGER IF EXISTS hash_test_native_field_event_outage ON events; DROP FUNCTION IF EXISTS hash_test_fail_native_field_event()`)
	}) //nolint:rawsql -- exact owned fixture objects only
	if w := post([]submitFieldValueInput{{FieldID: field.ID.String(), Value: "must roll back on real audit failure"}}); w.Code != http.StatusInternalServerError {
		t.Fatalf("actual audit failure status=%d", w.Code)
	}
	if snapshot() != before {
		t.Fatal("actual audit failure committed field or M94/chain state")
	}
	if _, err = f.pool.Exec(f.ctx, `DROP TRIGGER hash_test_native_field_event_outage ON events; DROP FUNCTION hash_test_fail_native_field_event()`); err != nil {
		t.Fatal(err)
	} //nolint:rawsql -- remove only controlled outage
	for _, value := range []string{"Reviewed A", "Reviewed A", "Reviewed B ÅÄÖ"} {
		if w := post([]submitFieldValueInput{{FieldID: field.ID.String(), Value: value}}); w.Code != http.StatusOK {
			t.Fatalf("repeated native autosave status=%d", w.Code)
		}
	}
	var events, measured int
	var value string
	var exact bool
	err = f.pool.QueryRow(f.ctx, `SELECT count(*),count(*) FILTER(WHERE m.event_id=e.id AND m.document_id=e.document_id AND m.org_id=e.org_id AND m.payload_wire_bytes=octet_length(e.payload_json::text) AND m.measurement_server_version_num=current_setting('server_version_num')::integer),(SELECT value FROM document_fields WHERE id=$3 AND document_id=$1),bool_and(e.recipient_id=$4 AND e.payload_json->>'notice_digest'=$5 AND NOT(e.payload_json?'value')) FROM events e LEFT JOIN html_snapshot_event_payload_sizes_v1 m ON m.event_id=e.id WHERE e.document_id=$1 AND e.org_id=$2 AND e.kind='document.field_filled'`, doc.ID, f.org, field.ID, party.ID, notice.NoticeDigest).Scan(&events, &measured, &value, &exact) //nolint:rawsql -- actual repeated writer/notice/privacy oracle
	if err != nil || events != 3 || measured != 3 || value != "Reviewed B ÅÄÖ" || !exact {
		t.Fatalf("repeated native autosave events/measurements/exact=%d/%d/%t err=%v", events, measured, exact, err)
	}
	current, err := f.q.GetDocument(f.ctx, generated.GetDocumentParams{ID: doc.ID, OrgID: f.org})
	if err != nil || current.PdfStorageKey != doc.PdfStorageKey || current.PdfStorageVersionID != doc.PdfStorageVersionID || !bytes.Equal(current.PdfSha256, doc.PdfSha256) {
		t.Fatal("autosave replaced approved PDF source", err)
	}
}
